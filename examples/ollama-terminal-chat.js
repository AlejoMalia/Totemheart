/**
 * Interactive terminal chat: Totemheart's real state + a real local Ollama
 * model, exactly the "Wiring it into a real LLM" pattern from the README.
 *
 * Two separate, real Ollama calls happen per turn, doing two different jobs:
 *   1. `OllamaProvider` (already in src/providers/) — Totemheart's own real
 *      appraisal/sentiment reads, via structured JSON prompts. This makes
 *      the emotional state itself smarter than the zero-dependency
 *      heuristic lexicon.
 *   2. A second, separate real Ollama /api/chat call — Totemheart has no
 *      text generator of its own (see README), so the actual reply PROSE
 *      you see is genuinely generated by the local model, steered by
 *      `result.systemPrompt` (dominant emotion, valence/arousal, cortisol,
 *      active defense mechanism, etc. — all real, computed this turn).
 *
 * Usage:
 *   node examples/ollama-terminal-chat.js [modelName]
 *   (defaults to llama3.2 — pass e.g. "qwen2.5:1.5b" to use the other one)
 */
import readline from 'node:readline'
import { Totemheart, Personality } from '../src/index.js'
import { OllamaProvider } from '../src/providers/OllamaProvider.js'

const MODEL = process.argv[ 2 ] || 'llama3.2'
const HOST     = 'http://localhost:11434'

async function ollamaChat( systemPrompt, history, userMessage ) {

	const res = await fetch( `${HOST}/api/chat`, {
		method  : 'POST',
		headers : { 'Content-Type': 'application/json' },
		body    : JSON.stringify( {
			model    : MODEL,
			stream   : false,
			messages : [
				{ role: 'system', content: systemPrompt },
				...history,
				{ role: 'user', content: userMessage },
			],
		} ),
	} )

	if ( !res.ok ) throw new Error( `Ollama /api/chat failed with status ${res.status}` )
	const data = await res.json()
	return data.message?.content ?? '(sin respuesta)'

}

async function main() {

	console.log( `Totemheart + Ollama (${MODEL}) — chat interactivo en terminal. Escribe "salir" para terminar.\n` )

	const ai = new Totemheart( {
		personality : new Personality( { openness: 0.7, extraversion: 0.6, agreeableness: 0.6, conscientiousness: 0.5, neuroticism: 0.4 } ),
		provider       : new OllamaProvider( { model: MODEL, host: HOST } ), // real LLM-based appraisal instead of the heuristic lexicon
	} )

	const history = []
	const rl = readline.createInterface( { input: process.stdin, output: process.stdout } )
	const ask = q => new Promise( resolve => rl.question( q, resolve ) )

	while ( true ) {

		const userMessage = await ask( 'Tú: ' )
		if ( userMessage.trim().toLowerCase() === 'salir' ) break
		if ( !userMessage.trim() ) continue

		let result
		try {

			result = await ai.processInput( userMessage, { userId: 'terminal-user' } )

		}
		catch ( err ) {

			console.error( `  (error real procesando el turno: ${err.message} — el pipeline no debería fallar así, es un bug si pasa)` )
			continue

		}

		console.log( `  [debug real: dominante=${ai.emotionSpace.getDominantEmotion()} valencia=${ai.emotionSpace.vector.valence.toFixed( 2 )} arousal=${ai.emotionSpace.vector.arousal.toFixed( 2 )} cortisol=${ai.cortisolEngine.getLevel().toFixed( 2 )}]` )

		let reply
		try {

			reply = await ollamaChat( result.systemPrompt, history, userMessage )

		}
		catch ( err ) {

			console.error( `  (Ollama /api/chat real falló: ${err.message} — ¿está "ollama serve" corriendo?)` )
			continue

		}

		console.log( `IA: ${reply}\n` )
		history.push( { role: 'user', content: userMessage }, { role: 'assistant', content: reply } )
		if ( history.length > 20 ) history.splice( 0, history.length - 20 ) // real, bounded context window

	}

	rl.close()
	console.log( '\nConversación terminada.' )

}

main().catch( err => { console.error( err ); process.exit( 1 ) } )
